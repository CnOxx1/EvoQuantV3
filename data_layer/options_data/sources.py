def _normalize_filter(values: list[str] | None) -> set[str]:
    return {
        value.strip().lower()
        for value in (values or [])
        if value.strip()
    }


def _split_csv(raw_value: str) -> list[str]:
    return [
        item.strip().upper()
        for item in raw_value.split(",")
        if item.strip()
    ]


def _load_extra_entities() -> list[dict[str, object]]:
    raw_value = OPTIONS_CONFIG.get("extra_entities_json", "").strip()
    if not raw_value:
        return []
    try:
        payload = json.loads(raw_value)
    except json.JSONDecodeError as exc:
        logger.error(f"解析 OPTIONS_EXTRA_ENTITIES_JSON 失败: {exc}")
        return []
    if not isinstance(payload, list):
        logger.error("OPTIONS_EXTRA_ENTITIES_JSON 必须是 JSON 数组")
        return []
    return [dict(item) for item in payload if isinstance(item, dict)]


