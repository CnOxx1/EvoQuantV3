def load_options_sources(
    source_names: list[str] | None = None,
    enabled_only: bool = True,
) -> list[OptionsSourceDefinition]:
    normalized_names = _normalize_filter(source_names)
    selected: list[OptionsSourceDefinition] = []
    for source in _build_default_options_sources():
        if enabled_only and not source.enabled:
            continue
        if normalized_names and source.source_name.lower() not in normalized_names:
            continue
        selected.append(source)
    return selected


